import { ethers } from "hardhat";
import fs from "fs";
import path from "path";

/**
 * GreenTrustChain
 * Canonical EVM receipt collector
 *
 * Purpose:
 *   Collect reproducible blockchain execution evidence without
 *   confusing dataset identifiers with blockchain transaction IDs.
 *
 * This file is deliberately independent of statistical analysis.
 * It records raw observations only.
 */

interface ReceiptRecord {
    model: string;

    datasetRowId: number;

    blockchainTransactionId: string;

    transactionHash: string;

    blockNumber: number;

    receiptStatus: number;

    gasUsed: string;

    effectiveGasPriceWei: string;

    gasCostWei: string;

    contractAddress: string;

    submittedAtUnixMs: number;

    confirmedAtUnixMs: number;

    confirmationLatencyMs: number;

    participantAddress: string;

    validatorAddress: string;

    datasetHash: string;

    experimentId: string;
}


/* ================================================================
                            CONFIGURATION
   ================================================================ */

const RESULT_DIR =
    path.join(
        process.cwd(),
        "results",
        "raw"
    );

const OUTPUT_FILE =
    path.join(
        RESULT_DIR,
        "canonical_receipts.jsonl"
    );

const EXPERIMENT_ID =
    process.env.EXPERIMENT_ID ??
    `exp-${Date.now()}`;


/* ================================================================
                        UTILITY FUNCTIONS
   ================================================================ */

function ensureResultDirectory(): void {

    fs.mkdirSync(
        RESULT_DIR,
        {
            recursive: true
        }
    );
}


function calculateGasCost(
    gasUsed: bigint,
    gasPrice: bigint
): bigint {

    return gasUsed * gasPrice;
}


/**
 * Convert a receipt into a deterministic experiment record.
 */
async function buildReceiptRecord(
    model: string,
    datasetRowId: number,
    blockchainTransactionId: bigint,
    tx: any,
    receipt: any,
    submittedAtUnixMs: number,
    contractAddress: string,
    participantAddress: string,
    validatorAddress: string,
    datasetHash: string
): Promise<ReceiptRecord> {

    const gasUsed =
        BigInt(
            receipt.gasUsed.toString()
        );

    const effectiveGasPrice =
        BigInt(
            (
                receipt.gasPrice ??
                receipt.effectiveGasPrice
            ).toString()
        );

    const gasCost =
        calculateGasCost(
            gasUsed,
            effectiveGasPrice
        );

    const confirmedAtUnixMs =
        Date.now();

    return {

        model,

        datasetRowId,

        blockchainTransactionId:
            blockchainTransactionId.toString(),

        transactionHash:
            tx.hash,

        blockNumber:
            receipt.blockNumber,

        receiptStatus:
            Number(
                receipt.status ?? 0
            ),

        gasUsed:
            gasUsed.toString(),

        effectiveGasPriceWei:
            effectiveGasPrice.toString(),

        gasCostWei:
            gasCost.toString(),

        contractAddress,

        submittedAtUnixMs,

        confirmedAtUnixMs,

        confirmationLatencyMs:
            confirmedAtUnixMs -
            submittedAtUnixMs,

        participantAddress,

        validatorAddress,

        datasetHash,

        experimentId:
            EXPERIMENT_ID
    };
}


/* ================================================================
                    TRANSACTION-ID EXTRACTION
   ================================================================ */

/**
 * Extract blockchain transaction ID from the contract event.
 *
 * This is critical.
 *
 * datasetRowId:
 *     Identifier in the CSV dataset.
 *
 * blockchainTransactionId:
 *     Identifier generated by the Solidity contract.
 *
 * They are independent identifiers.
 */
function extractTransactionId(
    receipt: any,
    contractInterface: any
): bigint {

    for (
        const log of receipt.logs
    ) {

        try {

            const parsed =
                contractInterface.parseLog({
                    topics: log.topics,
                    data: log.data
                });

            if (
                parsed &&
                parsed.name ===
                "TransactionSubmitted"
            ) {

                return BigInt(
                    parsed.args.transactionId.toString()
                );
            }

        } catch {
            /*
             * Ignore logs belonging to another contract
             * or unrelated events.
             */
        }
    }

    throw new Error(
        "TransactionSubmitted event not found."
    );
}


/* ================================================================
                    RECEIPT APPENDING
   ================================================================ */

function appendRecord(
    record: ReceiptRecord
): void {

    ensureResultDirectory();

    fs.appendFileSync(
        OUTPUT_FILE,
        JSON.stringify(record) + "\n"
    );
}


/* ================================================================
                    SINGLE TRANSACTION COLLECTOR
   ================================================================ */

/**
 * Collect one transaction execution.
 *
 * The function intentionally records:
 *
 *   datasetRowId
 *   blockchainTransactionId
 *   transactionHash
 *   blockNumber
 *   gasUsed
 *   gasPrice
 *   gasCost
 *   latency
 *
 * without calculating averages or performance scores.
 */
export async function collectReceipt(
    model: string,
    datasetRowId: number,
    blockchainTransactionId: bigint,
    tx: any,
    receipt: any,
    submittedAtUnixMs: number,
    contractAddress: string,
    participantAddress: string,
    validatorAddress: string,
    datasetHash: string
): Promise<ReceiptRecord> {

    const record =
        await buildReceiptRecord(
            model,
            datasetRowId,
            blockchainTransactionId,
            tx,
            receipt,
            submittedAtUnixMs,
            contractAddress,
            participantAddress,
            validatorAddress,
            datasetHash
        );

    appendRecord(record);

    return record;
}


/* ================================================================
                    DEMONSTRATION RUNNER
   ================================================================ */

async function main() {

    console.log(
        "\n=============================================="
    );

    console.log(
        " GreenTrustChain Receipt Collector"
    );

    console.log(
        "==============================================\n"
    );

    console.log(
        "Experiment ID:",
        EXPERIMENT_ID
    );

    /*
     * ------------------------------------------------------------
     * Signers
     * ------------------------------------------------------------
     */

    const [
        deployer,
        participant,
        validator
    ] =
        await ethers.getSigners();

    console.log(
        "Participant:",
        participant.address
    );

    console.log(
        "Validator:",
        validator.address
    );


    /*
     * ------------------------------------------------------------
     * Contract address
     * ------------------------------------------------------------
     */

    const address =
        process.env.DETERMINISTIC_ADDRESS;

    if (!address) {

        throw new Error(
            "DETERMINISTIC_ADDRESS environment variable is required."
        );
    }


    /*
     * ------------------------------------------------------------
     * Attach to deployed contract
     * ------------------------------------------------------------
     */

    const contract =
        await ethers.getContractAt(
            "DeterministicBaseline",
            address
        );


    /*
     * ------------------------------------------------------------
     * Dataset fingerprint
     * ------------------------------------------------------------
     *
     * This is supplied externally by the dataset-audit stage.
     * It should never be silently regenerated during analysis.
     * ------------------------------------------------------------
     */

    const datasetHash =
        process.env.DATASET_HASH;

    if (!datasetHash) {

        throw new Error(
            "DATASET_HASH environment variable is required."
        );
    }


    /*
     * ------------------------------------------------------------
     * Controlled demonstration transaction
     * ------------------------------------------------------------
     */

    const datasetRowId =
        Number(
            process.env.DATASET_ROW_ID ?? "0"
        );


    const submittedAtUnixMs =
        Date.now();


    const submitTx =
        await contract
            .connect(participant)
            .submitTransaction(
                "PROSUMER_001",
                1,
                1_250_000,
                998_000,
                25_000,
                10_000,
                150_000
            );


    const submissionReceipt =
        await submitTx.wait();

    if (!submissionReceipt) {

        throw new Error(
            "Submission receipt unavailable."
        );
    }


    /*
     * Obtain the actual blockchain transaction ID.
     */
    const blockchainTransactionId =
        extractTransactionId(
            submissionReceipt,
            contract.interface
        );


    console.log(
        "Dataset row:",
        datasetRowId
    );

    console.log(
        "Blockchain transaction ID:",
        blockchainTransactionId.toString()
    );


    /*
     * ------------------------------------------------------------
     * Execute transaction
     * ------------------------------------------------------------
     */

    const executionStart =
        Date.now();

    const executeTx =
        await contract
            .connect(validator)
            .executeTransaction(
                blockchainTransactionId
            );


    const executionReceipt =
        await executeTx.wait();

    if (!executionReceipt) {

        throw new Error(
            "Execution receipt unavailable."
        );
    }


    /*
     * ------------------------------------------------------------
     * Collect canonical receipt
     * ------------------------------------------------------------
     */

    const record =
        await collectReceipt(

            "deterministic",

            datasetRowId,

            blockchainTransactionId,

            executeTx,

            executionReceipt,

            executionStart,

            address,

            participant.address,

            validator.address,

            datasetHash
        );


    console.log(
        "\nReceipt collected successfully."
    );

    console.log(
        "Transaction hash:",
        record.transactionHash
    );

    console.log(
        "Block:",
        record.blockNumber
    );

    console.log(
        "Gas used:",
        record.gasUsed
    );

    console.log(
        "Gas cost (wei):",
        record.gasCostWei
    );

    console.log(
        "Latency (ms):",
        record.confirmationLatencyMs
    );

    console.log(
        "\nOutput:"
    );

    console.log(
        OUTPUT_FILE
    );
}


/* ================================================================
                            ENTRY POINT
   ================================================================ */

if (
    require.main === module
) {

    main().catch(
        (error) => {

            console.error(
                "\nReceipt collection failed:"
            );

            console.error(
                error
            );

            process.exitCode = 1;
        }
    );
}